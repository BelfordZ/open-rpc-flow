/**
 * Seeded PRNG (mulberry32). Kept inline so the mock handler needs no new
 * dependency; 32 bits of state are plenty for mock generation.
 */

/** Creates a deterministic random-number generator from a 32-bit seed. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
